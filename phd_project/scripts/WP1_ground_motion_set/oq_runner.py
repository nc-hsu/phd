SITE_MODEL_FILE = "site_model_casestudy_sites.csv"
SOURCE_MODEL_LOGIC_TREE_FILE = "source_model_logic_tree_eshm20.xml"

GMPE_LOGIC_TREES = {
    "03": "gmpe_logic_tree_AvgSA_0to3_median_branch.xml",
    "06": "gmpe_logic_tree_AvgSA_0to6_median_branch.xml",
}


def analysis_name(im: str, eps: int) -> str:
    """Manifest key for an analysis, e.g. ``AvgSA_03_psha_eps3``."""
    return f"AvgSA_{im}_psha_eps{eps}"


def config_name(im: str, eps: int) -> str:
    """Config filename for an analysis, e.g. ``config_AvgSA_03_psha_eps3.ini``."""
    return f"config_{analysis_name(im, eps)}.ini"


def im_upper(im: str) -> int:
    """Upper period of an AvgSA range key, e.g. ``"03"`` -> ``3``."""
    return int(im[-1])


def analysis_description(im: str, eps: int) -> str:
    """Engine description. Unique per analysis, which is what lets a calc_id be
    recovered from ``oq engine --list-hazard-calculations`` if stdout parsing fails.
    """
    return f"[ESHM20 AvgSA 0 to {im_upper(im)} - all sites - eps{eps}]"


def write_config(
    out_fp: Path,
    *,
    description: str,
    gsim_logic_tree_file: str,
    truncation_level: int,
    im_upper: int,
    site_model_file: str = SITE_MODEL_FILE,
    source_model_logic_tree_file: str = SOURCE_MODEL_LOGIC_TREE_FILE,
) -> Path:
    """Render a job ``.ini``. ``im_upper`` is the upper period of the AvgSA range
    (3 or 6) and is used only in the header comment. Returns the path written.
    """
    out_fp = Path(out_fp)
    text = _CONFIG_TEMPLATE.substitute(
        description=description,
        gsim_logic_tree_file=gsim_logic_tree_file,
        truncation_level=truncation_level,
        im_upper=im_upper,
        site_model_file=site_model_file,
        source_model_logic_tree_file=source_model_logic_tree_file,
    )
    out_fp.parent.mkdir(parents=True, exist_ok=True)
    # Skip a no-op rewrite so the mtime stays stable and the fingerprint below
    # does not churn on every notebook execution.
    if out_fp.is_file() and out_fp.read_text() == text:
        return out_fp
    out_fp.write_text(text)
    return out_fp


# Verbatim from regional_avgSA/config_eshm20_AvgSA_0to3_disagg_all_sites.ini, with
# two deliberate departures, both forced by the engine:
#
#   - intensity_measure_types_and_levels is *absent*. With iml_disagg set, the
#     engine infers the IMTLs from it and raises if both are given
#     (oqvalidation.py:1355-1359).
#   - poes_disagg is replaced by iml_disagg. The two are mutually exclusive
#     (oqvalidation.py:1590), and iml_disagg takes exactly one level per IMT
#     (oqvalidation.py:1352) - hence one config per IML.
#
# num_rlzs_disagg is written explicitly rather than left to default, because 0
# (= all realizations) is load-bearing: the mean disaggregation is only computed
# when Z > 1 (disaggregation.py:285). See write_disagg_config.
